	// They hold the weapon themselves -- stance, grip and finger pose are all
	// animated -- which is why the procedural weapon hold below is off. A pose
	// an animator authored beats one a solver reconstructs.
	//
	// Individual clips rather than the blendspaces beside them, because playing
	// a blendspace needs an animation graph to evaluate it. Single-node playback
	// is the honest floor: no strafe set and no turn-in-place, both of which are
	// in the source set waiting for a graph that can blend them.
