#!/usr/bin/env node
/**
 * Full proto-to-zod pipeline — single command to regenerate everything.
 *
 * 1. Compiles all .proto files to .binpb descriptors via protoc
 * 2. Generates Zod schemas from each descriptor + config
 *
 * Usage:
 *   npx tsx packages/data/codegen/gen-all.mjs            # all protos
 *   npx tsx packages/data/codegen/gen-all.mjs clickhouse  # single proto by name
 */

import { generateAndWriteZod } from '../../npm/devops/src/lib/codegen/index.js';
import { execSync } from 'node:child_process';
import { resolve, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import prettier from 'prettier';

const DENO_ZOD_IMPORT =
	"import { z } from 'https://deno.land/x/zod@v3.23.8/mod.ts';";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '../../..');
const protoRoot = resolve(__dirname, '../proto');
const descriptorsDir = resolve(__dirname, 'descriptors');
const generatedDir = resolve(__dirname, 'generated');

// The emitter writes readable-but-unformatted TS. Every commit path in this repo then runs a
// formatter over it (prettier via lint-staged, `deno fmt` for apps/kbve/edge), so raw emitter
// output never matches what is committed and `gen-all` reported ~50 formatting-only diffs on
// every run. Formatting here makes regeneration a no-op when nothing changed.
async function formatGenerated(filePath) {
	const info = await prettier.getFileInfo(filePath, {
		ignorePath: resolve(repoRoot, '.prettierignore'),
	});
	if (!info.ignored && info.inferredParser) {
		const config = await prettier.resolveConfig(filePath);
		const source = readFileSync(filePath, 'utf8');
		const formatted = await prettier.format(source, {
			...config,
			filepath: filePath,
		});
		if (formatted !== source) writeFileSync(filePath, formatted);
		return;
	}
	// Prettier-ignored paths are owned by another formatter; `deno fmt` is the only one in play.
	try {
		// cwd must sit under the deno.json that owns the file — `deno fmt` resolves its config
		// from the working directory, not from the path it is handed.
		execSync(`deno fmt "${filePath}"`, {
			stdio: 'pipe',
			cwd: dirname(filePath),
		});
	} catch {
		console.warn(
			`    ! ${relative(repoRoot, filePath)} is prettier-ignored and \`deno fmt\` is unavailable — left unformatted`,
		);
	}
}

import { protoRegistry as protos } from './lib/proto-registry.mjs';
import { hashProtoClosure } from './lib/proto-closure.mjs';

// Optional filter: pass a proto name as CLI arg to regenerate only that one
const filterName = process.argv[2];
const selected = filterName
	? protos.filter((p) => p.name === filterName)
	: protos;

if (filterName && selected.length === 0) {
	console.error(
		`Unknown proto: "${filterName}". Available: ${protos.map((p) => p.name).join(', ')}`,
	);
	process.exit(1);
}

console.log('=== Proto-to-Zod Pipeline ===\n');

// Step 1: Compile selected protos to .binpb
console.log('Step 1: Compiling protos to descriptors...');
for (const proto of selected) {
	const binpb = resolve(descriptorsDir, `${proto.name}.binpb`);
	const cmd = `protoc --include_imports --descriptor_set_out="${binpb}" --proto_path="${protoRoot}" ${proto.protoFile}`;
	try {
		execSync(cmd, { stdio: 'pipe' });
		console.log(`  ✓ ${proto.protoFile} → ${proto.name}.binpb`);
	} catch (err) {
		console.error(`  ✗ ${proto.protoFile} failed:`);
		console.error(err.stderr?.toString() || err.message);
		process.exit(1);
	}
}

// Record what each descriptor was built from, so `check-descriptors.mjs` can tell a stale
// artifact from a current one without needing protoc. Always rewritten for the FULL registry,
// even on a filtered run — a partial manifest would report untouched protos as untracked.
{
	const manifestPath = resolve(descriptorsDir, 'manifest.json');
	const manifest = {
		note: 'Generated by gen-all.mjs. Each hash covers the .proto and everything it imports; see codegen/lib/proto-closure.mjs. Verified by check-descriptors.mjs.',
		protos: Object.fromEntries(
			protos.map((p) => [
				p.name,
				hashProtoClosure(protoRoot, p.protoFile),
			]),
		),
	};
	mkdirSync(descriptorsDir, { recursive: true });
	writeFileSync(manifestPath, `${JSON.stringify(manifest, null, '\t')}\n`);
	console.log(`  ✓ manifest.json (${protos.length} protos)`);
}

// Step 2: Generate Zod schemas from each descriptor
console.log('\nStep 2: Generating Zod schemas...');
for (const proto of selected) {
	const configPath = resolve(__dirname, `${proto.name}-zod-config.json`);
	const descriptorPath = resolve(descriptorsDir, `${proto.name}.binpb`);
	const outputPath = proto.outputPath
		? resolve(__dirname, proto.outputPath)
		: resolve(generatedDir, `${proto.name}-schema.ts`);

	await generateAndWriteZod({
		descriptorPath,
		configPath,
		outputPath,
		protoPackage: proto.package,
	});
	await formatGenerated(outputPath);
	console.log(`  ✓ ${proto.name}-schema.ts`);

	for (const dest of proto.vendorTo ?? []) {
		const destPath = resolve(__dirname, dest.path);
		mkdirSync(dirname(destPath), { recursive: true });
		let body = readFileSync(outputPath, 'utf8');
		if (dest.denoZod) {
			body = body.replace(
				/^import \{ z \} from 'zod';$/m,
				DENO_ZOD_IMPORT,
			);
		}
		if (dest.astroZod) {
			body = body.replace(
				/^import \{ z \} from 'zod';$/m,
				"import { z } from 'astro/zod';",
			);
		}
		writeFileSync(destPath, body);
		await formatGenerated(destPath);
		console.log(`    ↳ vendored → ${dest.path}`);
	}
}

console.log('\n=== Done ===');
